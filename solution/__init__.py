"""Your solution.

The harness imports this package and calls `apply()` once, in the same process as `soup train`,
before Soup builds the model and the trainer. Patch whatever you need (transformers, peft,
bitsandbytes, Soup itself) so the training run uses your Triton kernels.

The rules in short (the README and the task statement have the full ones):
- your own `@triton.jit` kernels, defined in this folder, run in every measured run and together
  take >= 5% of the training time; the example's kernels (however renamed or rewritten) and
  kernels generated by torch.compile do not count;
- no ready-made kernel libraries (unsloth, liger-kernel, xformers, flash-attn, torchao, ...);
- the task stays the same: model, data, batches and their order, steps, LoRA, optimizer, Soup's
  settings and outputs; no other GPU, no background processes, no tricks with the measurement.
"""

from .add_rmsnorm import patch_qwen2_decoder_layer
from .head_patch import patch_head
from .layer_tail import patch_qwen2_layer_tail
from .nf4_dequant import patch_bnb_dequantize
from .recompute import patch_qwen2_mlp_adaptive_recompute, patch_qwen2_mlp_recompute
from .rmsnorm import patch_qwen2_rmsnorm
from .rope import patch_qwen2_rope
from .swiglu import patch_qwen2_mlp


def apply():
    patch_qwen2_mlp()  # the example: works out of the box, does not count as your own kernel
    patch_qwen2_mlp_recompute()  # C: MLP recomputation, off unless enabled (recompute.py)
    patch_qwen2_mlp_adaptive_recompute()  # experiment: recompute only dense batches (off by default)
    patch_qwen2_rmsnorm()  # B: fused RMSNorm (rmsnorm.py)
    patch_qwen2_rope()     # B: fused rotary embedding (rope.py)
    patch_qwen2_decoder_layer()  # F: residual add + norm fused (add_rmsnorm.py)
    patch_qwen2_layer_tail()  # Fuse the MLP residual with the following norm.
    patch_head()           # A: chunked output head + fused cross-entropy (ce_loss.py)
    patch_bnb_dequantize()  # E: NF4 weight dequantization (nf4_dequant.py)
